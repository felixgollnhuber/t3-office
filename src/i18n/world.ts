/** price on the coffee machine: one decimal below 10, no thousands separator, the display is 28 px wide */
const price = (cost: number) => {
  const digits = cost < 10 ? 1 : 0;
  return cost.toLocaleString(localeTag, { minimumFractionDigits: digits, maximumFractionDigits: digits, useGrouping: false });
};

